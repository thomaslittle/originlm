"""Generate the shared OriginLM brand primitives for CSS and GPUI."""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
data = json.loads((ROOT / 'brand/tokens.json').read_text())

def kebab(name):
    return re.sub(r'([A-Z])', r'-\1', name).lower()

css = ['/* Generated by scripts/generate_brand_tokens.py. */', ':root {',
       f'  --originlm-font: "{data["font"]}", -apple-system, "Segoe UI", sans-serif;']
rust = ['// Generated by scripts/generate_brand_tokens.py.',
        f'pub const FONT: &str = "{data["nativeFont"]}";']
for name, value in data['colors'].items():
    if not re.fullmatch(r'#[0-9a-f]{6}', value):
        raise ValueError(f'Invalid brand color: {name}')
    css.append(f'  --originlm-{kebab(name)}: {value};')
    if not name.startswith("scene"):
        rust.append(f'pub const {kebab(name).replace("-", "_").upper()}: u32 = 0x{value[1:]};')
css.append('}')
film = ['// Generated by scripts/generate_brand_tokens.py.', f'pub const FONT: &str = "{data["nativeFont"]}";']
for name in ['darkBackground', 'paper', 'amber', 'darkMuted']:
    film.append(f'pub const {kebab(name).replace("-", "_").upper()}: &str = "{data["colors"][name]}";')
outputs = {
    ROOT / 'media/video/src/brand.generated.rs': '\n'.join(film) + '\n',
    ROOT / 'apps/site/src/brand.generated.ts': '// Generated by scripts/generate_brand_tokens.py.\nexport const brand = ' + json.dumps(data['colors'], indent=2) + ' as const;\n',
    ROOT / 'brand/tokens.css': '\n'.join(css) + '\n',
    ROOT / 'crates/originlm-desktop/src/brand_tokens.rs': '\n'.join(rust) + '\n',
}
for path, expected in outputs.items():
    if '--check' in sys.argv:
        if not path.exists() or path.read_text() != expected:
            raise SystemExit(f'Brand tokens are stale: {path.relative_to(ROOT)}; run python scripts/generate_brand_tokens.py')
    elif not path.exists() or path.read_text() != expected:
        path.write_text(expected)
